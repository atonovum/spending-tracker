export function format(template, vars) {
  if (!vars) return template;
  return String(template).replace(/\{(\w+)\}/g, (_, key) => (key in vars ? vars[key] : `{${key}}`));
}

export function makeT(lang) {
  return (key, vars) => {
    const tpl = (DICT[lang] && DICT[lang][key]) || (DICT.ko && DICT.ko[key]) || key;
    return format(tpl, vars);
  };
}

export function formatMoney(value, lang = DEFAULT_LANGUAGE, currency) {
  const sign = value < 0 ? "-" : "";
  const abs = Math.round(Math.abs(value));
  const resolvedCurrency = currency || (lang === "ko" ? "KRW" : "USD");
  const valueStr = abs.toLocaleString(resolvedCurrency === "KRW" ? "ko-KR" : "en-US");
  
  if (resolvedCurrency === "KRW") {
    if (lang === "ko") return `${sign}${valueStr}원`;
    return `${sign}￦${valueStr}`;
  }
  return `${sign}$${valueStr}`;
}

const I18nContext = createContext({
  lang: DEFAULT_LANGUAGE,
  currency: DEFAULT_CURRENCY,
  t: makeT(DEFAULT_LANGUAGE),
  formatMoney: (value) => formatMoney(value, DEFAULT_LANGUAGE, DEFAULT_CURRENCY),
});

export function I18nProvider({ lang, currency = DEFAULT_CURRENCY, children }) {
  const resolvedCurrency = currency === "USD" ? "USD" : "KRW";
  const value = useMemo(() => ({
    lang,
    currency: resolvedCurrency,
    t: makeT(lang),
    formatMoney: (value) => formatMoney(value, lang, resolvedCurrency),
  }), [lang, resolvedCurrency]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}

export function useT() {
  const { t } = useContext(I18nContext);

  // Return an enhanced translation function that supports language override
  return (key, varsOrLang) => {
    // If second param is a string matching a language key, treat it as language override
    if (typeof varsOrLang === 'string' && (varsOrLang === 'ko' || varsOrLang === 'en')) {
      const tLang = makeT(varsOrLang);
      return tLang(key);
    }
    // Otherwise, use normal translation with vars
    return t(key, varsOrLang);
  };
}
